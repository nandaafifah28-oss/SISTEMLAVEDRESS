CREATE TRIGGER apply_return_dress_status
AFTER INSERT ON returns
FOR EACH ROW
EXECUTE FUNCTION apply_return_dress_status();

-- PostgreSQL cannot replace a view when the new SELECT removes or reorders
-- existing columns. This view is read-only and has no schema dependencies.

DROP VIEW IF EXISTS public.v_dress_inventory;

CREATE VIEW public.v_dress_inventory AS
SELECT
  d.id,
  d.dress_code,
  d.name,
  d.size,
  d.color,
  d.purchase_price,
  d.rental_price,
  d.condition,
  d.status,
  d.is_active,
  d.photo_url,
  d.description,
  c.category_name,
  s.name supplier_name
FROM dresses d
LEFT JOIN dress_categories c ON c.id=d.category_id
LEFT JOIN suppliers s ON s.id=d.supplier_id
WHERE d.is_active;

