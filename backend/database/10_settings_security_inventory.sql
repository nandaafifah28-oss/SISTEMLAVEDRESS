CREATE OR REPLACE FUNCTION current_app_role()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT lower(
    coalesce(
      (
        SELECT role
        FROM app_users
        WHERE auth_user_id = auth.uid()
          AND is_active
      ),
      'staff'
    )
  );
$$;

CREATE OR REPLACE FUNCTION write_audit_log(
  p_action text,
  p_module text,
  p_record_id text,
  p_old jsonb DEFAULT NULL,
  p_new jsonb DEFAULT NULL
)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO audit_logs(
    user_id,
    action,
    module,
    record_id,
    old_value,
    new_value
  )
  VALUES(
    auth.uid(),
    p_action,
    p_module,
    p_record_id,
    p_old,
    p_new
  );
$$;

CREATE OR REPLACE FUNCTION audit_dress_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM write_audit_log(
      'CREATE',
      'Dress',
      NEW.id::text,
      NULL,
      to_jsonb(NEW)
    );
  ELSIF TG_OP = 'UPDATE' THEN
    PERFORM write_audit_log(
      'UPDATE',
      'Dress',
      NEW.id::text,
      to_jsonb(OLD),
      to_jsonb(NEW)
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS audit_dress_change ON dresses;

CREATE TRIGGER audit_dress_change
AFTER INSERT OR UPDATE ON dresses
FOR EACH ROW
EXECUTE FUNCTION audit_dress_change();
CREATE OR REPLACE FUNCTION record_dress_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO dress_movements(
      dress_id,
      movement_type,
      status_before,
      status_after,
      description
    )
    VALUES(
      NEW.id,
      'MASTER_CREATE',
      NULL,
      NEW.status,
      'Dress dibuat dari Master Dress'
    );
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO dress_movements(
      dress_id,
      movement_type,
      status_before,
      status_after,
      description
    )
    VALUES(
      NEW.id,
      'STATUS_CHANGE',
      OLD.status,
      NEW.status,
      'Status dress berubah'
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS record_dress_movement ON dresses;

CREATE TRIGGER record_dress_movement
AFTER INSERT OR UPDATE OF status ON dresses
FOR EACH ROW
EXECUTE FUNCTION record_dress_movement();

CREATE OR REPLACE FUNCTION apply_return_dress_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  target_status varchar(30);
BEGIN
  target_status := CASE NEW.condition
    WHEN 'Baik' THEN 'Available'
    WHEN 'Kotor' THEN 'Laundry'
    WHEN 'Rusak Ringan' THEN 'Repair'
    WHEN 'Rusak Berat' THEN 'Not Available'
    ELSE 'Available'
  END;

  UPDATE dresses
  SET status = target_status
  WHERE id IN (
    SELECT dress_id
    FROM rental_details
    WHERE rental_id = NEW.rental_id
  );

  RETURN NEW;
END;
$$;

