  dress_variant_id,
  movement_type,
  reference_code,
  status_before,
  status_after,
  quantity_delta,
  available_delta,
  rented_delta,
  unavailable_delta,
  description
)
SELECT
  variant.dress_id,
  variant.id,
  'MIGRATION_OPENING',
  'MIGRATION-24',
  NULL,
  variant.status,
  variant.quantity,
  variant.available_quantity,
  variant.rented_quantity,
  variant.unavailable_quantity,
  'Saldo awal varian dari migrasi inventory per ukuran'
FROM public.dress_variants variant
WHERE variant.quantity > 0
  AND NOT EXISTS (
    SELECT 1
    FROM public.dress_movements movement
    WHERE movement.dress_variant_id = variant.id
      AND movement.movement_type = 'MIGRATION_OPENING'
      AND movement.reference_code = 'MIGRATION-24'
  );

